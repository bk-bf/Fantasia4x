const parse = (src: Record<string, string>): Font =>
  Object.fromEntries(
    Object.entries(src).map(([k, v]) => {
      const rows = v.split(' ');
      const w = rows[0].length;
      while (rows.length < 9) rows.push('.'.repeat(w));
      return [k, rows];
    })
  );

export const FX_FONT = { thin: parse(thin), bold: parse(bold) };
