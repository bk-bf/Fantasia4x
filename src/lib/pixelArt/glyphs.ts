export type GlyphName = keyof typeof GLYPHS;

const SIZE = 11;

function cells(name: GlyphName) {
  const g = GLYPHS[name];
  return (x: number, y: number) => x >= 0 && y >= 0 && x < SIZE && y < SIZE && g[y][x] === '#';
}

export function glyph(name: GlyphName, ramp: Ramp, line: Rgb | null = INK): HTMLCanvasElement {
  const on = cells(name);
  const n = ramp.length - 1;
  return paint(SIZE + 2, SIZE + 2, (X, Y) => {
    const x = X - 1;
    const y = Y - 1;
    if (on(x, y)) {
      const hi = !on(x, y - 1) || !on(x - 1, y);
      const lo = !on(x, y + 1) || !on(x + 1, y);
      return ramp[clamp(n - 1 + (hi && !lo ? 1 : 0) - (lo && !hi ? 2 : 0), 0, n)];
    }
    if (!line) return null;
    for (let j = -1; j <= 1; j++)
      for (let i = -1; i <= 1; i++) if ((i || j) && !(i && j) && on(x + i, y + j)) return line;
    return null;
  });
}

export interface BadgeOptions {
  line?: Rgb;
  fg?: Rgb;
  fill?: number;
}

export function badge(name: GlyphName, ramp: Ramp, o: BadgeOptions = {}): HTMLCanvasElement {
  const on = cells(name);
  const n = ramp.length - 1;
  return paint(17, 17, (x, y) => {
    const d = Math.min(x, y, 16 - x, 16 - y);
    if (d === 0) return (x === 0 || x === 16) && (y === 0 || y === 16) ? null : (o.line ?? INK);
    if (on(x - 3, y - 3)) return o.fg ?? ramp[!on(x - 3, y - 4) || !on(x - 4, y - 3) ? n : n - 1];
    if (on(x - 4, y - 4)) return ramp[0];
    if (d === 1) return ramp[y === 1 || x === 1 ? 3 : 1];
    return pick(ramp, (o.fill ?? 0.3) + (hash(x, y, 7) - 0.5) * 0.12, x, y, 0.8);
  });
}
